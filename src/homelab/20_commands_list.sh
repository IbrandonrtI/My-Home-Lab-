commands() {
  # keep every description short: a section prints as a table only if its longest line fits the window (about 100 columns)
  # each section is in alphabetical order (not counting "sudo")
  section "Start here"
  cmd "docker ps"                      "what is running right now, and how healthy it is"
  cmd "sudo drives status"             "pools, drives, SMART health, free space, last backup"
  cmd "homelab"                        "this machine at a glance: status and what to do next"
  cmd "sudo homelab-backup"            "run the backup now (about a minute, longer after many new files)"
  cmd "sudo homelab-setup upgrade"     "update the lab: new files from GitHub, new scripts here"
  cmd "sudo homelab-update check"      "look online for newer container images (changes nothing)"
  section "Which check do I run?"
  cmd "sudo drives check"              "scan the pool drives for file system errors (changes nothing)"
  cmd "sudo drives health"             "SMART health, temperature and wear of every drive"
  cmd "homelab status"                 "a quick look at everything (the login screen, live)"
  cmd "homelab-check ~/My-Home-Lab-"   "the repository files only, before an upload (not the server)"
  cmd "sudo homelab-selftest"          "the big check of the whole lab (report saved in ~)"
  cmd "sudo homelab-setup verify"      "does every container and service answer?"
  section "Drives: the main ones"
  cmd "df -h /"                        "free space on the boot drive (the one the system runs from)"
  cmd "sudo drives"                    "menu: look at, connect, remove or fix drives"
  cmd "sudo drives connect"            "add a new drive to the main or backup storage (asks before erasing)"
  cmd "sudo drives disconnect"         "take a drive out of a storage, copying its files to the others first"
  cmd "sudo drives list"               "one line per drive: name, size, pool, state"
  cmd "sudo drives recover"            "after an unplug or power cut: remount, restart containers"
  cmd "sudo drives replace"            "a drive died: swap it, restore the files from the backup"
  cmd "sudo drives usage"              "space used and free, per drive and per pool"
  cmd "sudo drives wizard"             "suggest a ready-made setup (drives with files too)"
  cmd "findmnt /mnt/storage"           "is the main pool connected? (prints nothing if not)"
  section "More drive commands"
  cmd "sudo drives adopt"              "turn the old single data drive into a pool"
  cmd "sudo drives balance"            "even out the files over one storage's drives (shows the plan)"
  cmd "sudo drives bootsection"        "use part of the boot drive for a pool (size limit, used last)"
  cmd "sudo drives cache"              "add an SSD read cache to a ZFS array"
  cmd "sudo drives eject"              "get a spare drive ready to unplug"
  cmd "sudo drives fillorder"          "how new files pick a drive (one by one or spread), and the order"
  cmd "sudo drives help"               "every drive command with its options (sudo drives help NAME)"
  cmd "sudo drives limit"              "how much free space a drive keeps before the next is used"
  cmd "sudo drives move"               "move a drive between the main and the backup storage"
  cmd "sudo drives power"              "re-apply the drive power settings"
  cmd "sudo drives preset"             "ready-made setups on empty drives: pool, SnapRAID, ZFS, RAID"
  cmd "sudo drives release"            "take all drives out of the pools (files stay on the drives)"
  cmd "sudo drives rename"             "give a pool drive a name of your own"
  cmd "sudo drives resize"             "change the size of a boot drive section"
  cmd "sudo drives restore"            "copy back only the files that are missing from the backup"
  cmd "sudo drives sleep"              "spin a drive down now (sudo drives wake wakes it)"
  cmd "sudo drives snapraid"           "SnapRAID by hand: status, diff, sync or scrub"
  cmd "sudo drives spare"              "add a hot spare drive to a ZFS or RAID array"
  cmd "sudo drives timeshift"          "stop Timeshift copying the boot drive sections"
  cmd "sudo drives wipe"               "erase a spare drive that is not in a pool"
  section "Backup"
  cmd "sudo homelab-restore-configs check" "after a rebuild: preview restoring saved settings"
  cmd "sudo tail -f /var/log/homelab-backup.log" "watch a backup while it runs (Ctrl+C to leave)"
  section "Containers and updates"
  cmd "docker logs --tail 50 NAME"     "the last 50 lines a container printed"
  cmd "docker restart NAME"            "restart one container"
  cmd "docker stats --no-stream"       "CPU and memory of each container"
  cmd "sudo homelab-update"            "check, download, then update each stack (asks first)"
  cmd "sudo homelab-update clean"      "delete old saved versions and leftover images (asks first)"
  cmd "homelab-update list"            "what is waiting, and the order to update in (no sudo)"
  section "System and network"
  cmd "sudo apt update && sudo apt upgrade" "install the waiting system updates"
  cmd "sudo reboot"                    "restart the server (afterwards: sudo drives status)"
  cmd "tailscale status"               "who is on your private network"
  section "Homepage dashboard"
  cmd "homelab bookmark add NAME URL [CATEGORY]" "add one (optional too: ICON LINK, NUMBER)"
  cmd "homelab bookmark list"          "the bookmarks, by category, with their numbers"
  cmd "homelab bookmark move NAME CATEGORY" "another category (add a NUMBER for its place)"
  cmd "homelab bookmark remove NAME [CATEGORY]" "take one away (CATEGORY if the name is in two)"
  cmd "homelab calendar add NAME ADDRESS" "show an online calendar (Google, school ...)"
  cmd "homelab calendar list"          "your online calendars (also: remove N, sync)"
  cmd "homelab event add DATE \"text\" [yearly]" "your own event in the calendar"
  cmd "homelab event list"             "your events, numbered (remove: event remove NUMBER)"
  cmd "homelab simple on|off"          "hide the small text under card names (default: off)"
  cmd "homelab theme"                  "show the look and how to change it (no sudo)"
  cmd "homelab theme background [BLUR] URL" "new picture; optional BLUR: none sm md lg xl 2xl 3xl"
  cmd "homelab theme cards COLOR NUMBER" "ALL cards: colour, how solid (NUMBER 0 to 100)"
  cmd "homelab theme cards SERVICE COLOR" "ONE card, e.g. AdGuard Home blue"
  cmd "homelab theme links GROUP COLOR" "colour of one bookmark group, e.g. Productivity green"
  cmd "homelab theme reset"            "the shipped look again"
  cmd "sudo homelab-cards"             "give new services (containers with a web page) a card"
  cmd "sudo homelab-cards ignore NAME" "never make a card for this container"
  cmd "sudo homelab-cards list"        "the cards it made, and what it waits for"
  cmd "sudo homelab-cards move NAME SECTION" "put a card in another section"
  if command -v homelab-setup >/dev/null 2>&1; then
    section "Setup checklist"
    cmd "sudo homelab-setup"             "the checklist: what is done and what is left"
    cmd "sudo homelab-setup --details"   "the full instructions of every open step"
    cmd "sudo homelab-setup adguard"     "add AdGuard Home, if you skipped it during the install"
    cmd "sudo homelab-setup done STEP"   "mark a step you did by hand as done (see the checklist)"
    cmd "sudo homelab-setup fill"        "walk through the logins and keys that need you"
    cmd "sudo homelab-setup growdisk"    "use the drive's unused space for the system (LVM; asks first)"
    cmd "sudo homelab-setup install"     "set everything up, or carry on after a failure (safe to repeat)"
    cmd "sudo homelab-setup refresh"     "re-check, and continue every step that is now possible"
    cmd "sudo homelab-setup secrets"     "show the generated passwords and keys once more"
    cmd "sudo homelab-setup skip STEP"   "mark an optional step as not wanted"
    cmd "sudo homelab-setup verify"      "check that every container and service is up"
  fi
  section "Rebuild and safety"
  cmd "homelab secrets"                "rebuild check: passwords you must have, and what is backed up"
  section "This screen and the guides"
  cmd "homelab commands"               "this list"
  cmd "homelab docs"                   "sections of the README and the guides in docs/"
  cmd "homelab status"                 "only the status block"
  section "Short forms"
  cmd "homelab backup"                 "the same as: sudo homelab-backup (also update, cards, selftest)"
  cmd "homelab drives"                 "the same as: sudo drives (add a command: homelab drives health)"
  cmd "homelab upgrade"                "the same as: sudo homelab-setup upgrade"
  section "Words used here"
  cmd "Backup / Main"                  "Main holds your files; Backup holds the nightly copy of them"
  cmd "boot drive"                     "the drive the system itself runs from"
  cmd "container"                      "an app running in Docker; a stack is a group of them"
  cmd "mirror, SnapRAID, ZFS, RAID"    "ways to keep your files if a drive dies (sudo drives wizard)"
  cmd "pool"                           "several drives shown as one folder (Main: /mnt/storage)"
  cmd "SMART"                          "a drive's own health report: temperature, bad sectors, wear"
  flush_cmds
}

